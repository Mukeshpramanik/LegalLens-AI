export async function handleCompareDocuments(req: Request, res: Response, next: NextFunction): Promise<void> {
  try {
    const authReq = req as AuthenticatedRequest;
    const userId = authReq.user!.uid;
    const parsedA = uuidSchema.safeParse(req.body.documentIdA);
    const parsedB = uuidSchema.safeParse(req.body.documentIdB);
    if (!parsedA.success || !parsedB.success) {
      throw new AppError('Invalid Document ID format for comparison', 400, 'INVALID_PARAM');
    }
    const documentIdA = parsedA.data;
    const documentIdB = parsedB.data;

    const docA = await FirestoreService.getDocumentById(userId, documentIdA);
    const docB = await FirestoreService.getDocumentById(userId, documentIdB);

    if (!docA || !docB) {
      throw new AppError('One or both documents not found or unauthorized', 404, 'NOT_FOUND');
    }

    let docAText: string, docBText: string;
    try {
      docAText = await StorageService.getExtractedText(userId, documentIdA);
      docBText = await StorageService.getExtractedText(userId, documentIdB);
    } catch (err) {
      throw new AppError('Could not retrieve extracted text for comparison', 500, 'STORAGE_ERROR');
    }

    if (!docAText || !docBText) {
      throw new AppError('One or both documents have no extractable text', 400, 'EMPTY_TEXT');
    }

    try {
      const comparisonResult = await GeminiService.compareDocuments(
        userId,
        documentIdA,
        documentIdB,
        docA.originalName,
        docB.originalName,
        docAText,
        docBText
      );

      await FirestoreService.saveComparisonResult(comparisonResult);

      res.json({
        success: true,
        data: comparisonResult,
      });
    } catch (err) {
      const errorMessage = err instanceof Error ? err.message : 'Unknown AI error';
      Logger.error('Gemini comparison execution failed', { error: errorMessage });
      let statusCode = 500;
      let errorCode = 'AI_ERROR';
      if (errorMessage.includes('quota') || errorMessage.includes('rate limit') || errorMessage.includes('429')) {
        statusCode = 429;
        errorCode = 'QUOTA_EXCEEDED';
      } else if (errorMessage.includes('503') || errorMessage.includes('unavailable') || errorMessage.includes('high demand')) {
        statusCode = 503;
        errorCode = 'SERVICE_UNAVAILABLE';
      }
      throw new AppError(errorMessage, statusCode, errorCode);
    }
  } catch (error) {
    next(error);
  }
}
